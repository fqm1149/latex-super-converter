/**
 * LaTeX 分隔符转换核心
 * ---------------------------------------------------------------
 * 把非 Obsidian(MathJax) 兼容的 LaTeX 分隔符转换为 $ / $$：
 *   \( ... \)   -> $ ... $
 *   \[ ... \]   -> $$ ... $$
 *
 * 设计要点：
 * 1. 跳过 frontmatter、围栏代码块、行内代码、wikilink、HTML 注释，
 *    避免改坏代码与链接。
 * 2. 跳过已有的 $ / $$ 公式内部，避免嵌套破坏。
 * 3. 只做「成对」转换：找不到配对就保持原样，不制造孤立的 $。
 * 4. 新生成的 $$ 块独占行（两侧有文字时插入换行），这是 Obsidian
 *    Live Preview 渲染最稳的写法；已存在的 $$ 块不动。
 * 5. 空公式 \[\] 直接删除。
 */

