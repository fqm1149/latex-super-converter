#!/usr/bin/env node
"use strict";
/**
 * 零依赖打包器：把 src/converter.js + src/bare.js + src/plugin.js
 * 合并成 Obsidian 可直接加载的 main.js。纯 Node 字符串处理，不需要 npm install。
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");

function stripModule(src) {
  return src
    .replace(/^\s*"use strict";\s*/m, "")
    .replace(/\n?module\.exports\s*=\s*\{[\s\S]*?\};?\s*$/m, "")
    .replace(/\n?module\.exports\s*=\s*_export;\s*\nmodule\.exports\.default\s*=\s*_export;\s*$/m, "")
    .trim();
}

let converter = stripModule(read("src/converter.js"));
let bare = stripModule(read("src/bare.js"));
let plugin = stripModule(read("src/plugin.js"));

// bare.js 里的 __collectSkipRanges 兜底 require 在打包后不需要（同作用域已定义）
bare = bare.replace(
  /const __collectSkipRanges =\s*\n?[\s\S]*?require\("\.\/converter\.js"\)\.collectSkipRanges;/m,
  "const __collectSkipRanges = collectSkipRanges;"
);

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY scripts/build.js
Plugin: LaTeX Super Converter
Generated: ${new Date().toISOString()}
Sources: src/converter.js + src/bare.js + src/plugin.js
*/
`;

const out = [
  banner,
  '"use strict";',
  "",
  "/* ===================== 1. delimiter converter ===================== */",
  converter,
  "",
  "/* ===================== 2. bare formula recognizer ===================== */",
  bare,
  "",
  "/* ===================== 3. plugin entry ===================== */",
  plugin,
  "",
  "module.exports = LatexSuperConverterPlugin;",
  "module.exports.default = LatexSuperConverterPlugin;",
  "",
].join("\n");

fs.writeFileSync(path.join(root, "main.js"), out, "utf8");
console.log("built main.js:", out.length, "bytes");
