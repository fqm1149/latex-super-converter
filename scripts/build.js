#!/usr/bin/env node
"use strict";
/**
 * 零依赖打包器：把 src/converter.js + src/bare.js + src/plugin.js
 * 合并成 Obsidian 可直接加载的 main.js。纯 Node 字符串处理，不需要 npm install。
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");

function stripModule(src) {
  return src
    .replace(/^\s*"use strict";\s*/m, "")
    .replace(/\n?module\.exports\s*=\s*\{[\s\S]*?\};?\s*$/m, "")
    .replace(/\n?module\.exports\s*=\s*_export;\s*\nmodule\.exports\.default\s*=\s*_export;\s*$/m, "")
    .trim();
}

let converter = stripModule(read("src/converter.js"));
let bare = stripModule(read("src/bare.js"));
let integrity = stripModule(read("src/integrity.js"));
let i18n = stripModule(read("src/i18n.js"));
let plugin = stripModule(read("src/plugin.js"));

/**
 * 源码里为了让「单独跑测试」和「打包后同作用域」两种模式都能工作，写了这种兜底：
 *
 *   const _foo = typeof foo === "function" ? foo : require("./x.js").foo;
 *
 * 打包后 foo 一定在同一作用域里，require 分支永远不会走到，但留在产物里
 * 既难看又会让静态检查误报。这里统一折叠成 `const _foo = foo;`。
 */
const FALLBACK_RE =
  /const (\w+) =\s*\n?\s*typeof (\w+) === "function"\s*\n?\s*\? \2\s*\n?\s*: require\("[^"]+"\)\.\w+;/g;

function inlineFallbacks(src) {
  return src.replace(FALLBACK_RE, "const $1 = $2;");
}

bare = inlineFallbacks(bare);
integrity = inlineFallbacks(integrity);
plugin = inlineFallbacks(plugin);

// 注意：banner 里不能写入时间戳等每次都变的字段，
// 否则同一份源码每次构建出的 main.js 哈希都不同，无法做可复现构建校验。
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY scripts/build.js
Plugin: LaTeX Super Converter
Sources: src/converter.js + src/bare.js + src/integrity.js + src/i18n.js + src/plugin.js
*/
`;

const out = [
  banner,
  '"use strict";',
  "",
  "/* ===================== 1. delimiter converter ===================== */",
  converter,
  "",
  "/* ===================== 2. bare formula recognizer ===================== */",
  bare,
  "",
  "/* ===================== 3. write-back integrity check ===================== */",
  integrity,
  "",
  "/* ===================== 4. i18n ===================== */",
  i18n,
  "",
  "/* ===================== 5. plugin entry ===================== */",
  plugin,
  "",
  "module.exports = LatexSuperConverterPlugin;",
  "module.exports.default = LatexSuperConverterPlugin;",
  "",
].join("\n");

fs.writeFileSync(path.join(root, "main.js"), out, "utf8");
console.log("built main.js:", out.length, "bytes");
